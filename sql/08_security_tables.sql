\set ON_ERROR_STOP on

BEGIN;

CREATE TABLE IF NOT EXISTS app_local_users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    username            varchar(100) NOT NULL,
    display_name        varchar(200) NOT NULL,
    password_hash       text NOT NULL,
    role                varchar(30) NOT NULL,
    enabled             boolean NOT NULL DEFAULT true,
    emergency_admin     boolean NOT NULL DEFAULT false,
    expires_at          timestamp without time zone,
    failed_attempts     integer NOT NULL DEFAULT 0,
    locked_until        timestamp without time zone,
    last_login_at       timestamp without time zone,
    created_at          timestamp without time zone
                        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          varchar(100) NOT NULL,
    updated_at          timestamp without time zone
                        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          varchar(100) NOT NULL,

    CONSTRAINT pk_app_local_users
        PRIMARY KEY (id),

    CONSTRAINT uq_app_local_users_username
        UNIQUE (username),

    CONSTRAINT ck_app_local_users_role
        CHECK (
            role IN (
                'ASPEN.Reader',
                'ASPEN.Operator',
                'ASPEN.Admin'
            )
        )
);


CREATE TABLE IF NOT EXISTS app_emergency_mode (
    id              smallint NOT NULL DEFAULT 1,
    enabled         boolean NOT NULL DEFAULT false,
    enabled_at      timestamp without time zone,
    enabled_by      varchar(100),
    expires_at      timestamp without time zone,
    reason          text,
    disabled_at     timestamp without time zone,
    disabled_by     varchar(100),

    CONSTRAINT pk_app_emergency_mode
        PRIMARY KEY (id),

    CONSTRAINT ck_app_emergency_mode_singleton
        CHECK (id = 1)
);


INSERT INTO app_emergency_mode (
    id,
    enabled
)
VALUES (
    1,
    false
)
ON CONFLICT (id) DO NOTHING;


CREATE TABLE IF NOT EXISTS app_audit_log (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at             timestamp without time zone
                            NOT NULL DEFAULT CURRENT_TIMESTAMP,
    username                varchar(100),
    display_name            varchar(200),
    authentication_type     varchar(30),
    role                    varchar(30),
    action                  varchar(100) NOT NULL,
    target_type             varchar(100),
    target_id               varchar(100),
    result                  varchar(20) NOT NULL,
    source_ip               varchar(64),
    reason                  text,
    details                 text,

    CONSTRAINT pk_app_audit_log
        PRIMARY KEY (id),

    CONSTRAINT ck_app_audit_log_result
        CHECK (
            result IN (
                'SUCCESS',
                'FAILURE',
                'DENIED'
            )
        )
);


CREATE INDEX IF NOT EXISTS
    ix_app_audit_log_occurred_at
ON app_audit_log (
    occurred_at DESC
);


CREATE INDEX IF NOT EXISTS
    ix_app_audit_log_username
ON app_audit_log (
    username
);


CREATE INDEX IF NOT EXISTS
    ix_app_local_users_enabled
ON app_local_users (
    enabled,
    expires_at
);


COMMIT;
